import assert from 'node:assert/strict';
import {viaReverseNormalize,viaReverseHandle} from '../addons/via-reverse-api.mjs';
import {viaReverseUsable,viaReverseRace} from '../addons/via-reverse-bridge.mjs';
const lat=-34.9061,lng=-56.1999;
const feature={geometry:{coordinates:[lng,lat]},properties:{country_code:'uy',street:'Plaza Independencia',housenumber:'743',result_type:'building',city:'Montevideo',state:'Montevideo'}};
assert.equal(viaReverseNormalize({features:[feature]},lat,lng)[0].street,'Plaza Independencia 743');
assert.equal(viaReverseNormalize({features:[{...feature,properties:{...feature.properties,result_type:'street'}}]},lat,lng)[0].street,'Plaza Independencia');
assert.equal(viaReverseNormalize({features:[{...feature,properties:{...feature.properties,country_code:'ar'}}]},lat,lng).length,0);
assert.equal(viaReverseNormalize({features:[{...feature,geometry:{coordinates:[lng,lat+.02]}}]},lat,lng).length,0);
assert.equal((await viaReverseHandle(new Request('https://test/api/via-reverse'),{})).status,400);
const row=viaReverseNormalize({features:[feature]},lat,lng);
assert(viaReverseUsable(row,lat,lng));assert(!viaReverseUsable([...row,{...row[0],street:'Otra calle'}],lat,lng));
const req=new Request('https://test/api/direcciones?mode=reverse&lat='+lat+'&lng='+lng);
const reply=(results,status=200)=>new Response(JSON.stringify({results}),{status});
let secondary=0;
const env={VIA_POI_API:{fetch:async()=>{secondary++;return reply(row)}}};
const fast=await viaReverseRace(req,env,{fetch:async()=>reply(row)},{});assert.equal(fast.status,200);assert.equal(secondary,0);
const backup=await viaReverseRace(req,env,{fetch:async()=>reply([],503)},{});assert.equal(backup.status,200);assert.equal(secondary,1);
const slow=await viaReverseRace(req,env,{fetch:async()=>{await new Promise(r=>setTimeout(r,1600));return reply([],503)}},{});assert.equal(slow.status,200);assert.equal(secondary,2);
console.log('VIA_REVERSE_UNIT_PASS validation, distance, approximate number, ambiguity, fast primary, outage fallback');
