import assert from 'node:assert/strict';
import {reverseCacheIdentity,reverseCacheRead,reverseCacheWrite} from '../addons/via-reverse-cache.mjs';
import {viaReverseRace} from '../addons/via-reverse-bridge.mjs';
import {DatabaseSync} from 'node:sqlite';
import {readFileSync} from 'node:fs';
const sqlite=new DatabaseSync(':memory:');sqlite.exec(readFileSync('qa/reverse-reference-cache.sql','utf8'));
const db={prepare(sql){const st=sqlite.prepare(sql);return {bind(...v){return {async first(){return st.get(...v)},async run(){return st.run(...v)}}}}}};
const lat=-34.9061,lng=-56.1999;
const rows=[{street:'Plaza Independencia 743',lat:lat+.0001,lng,city:'Montevideo',department:'Montevideo',source:'Geoapify',distanceMeters:0,accountId:'not stored',private:'discard'}];
const id=await reverseCacheIdentity(lat,lng),same=await reverseCacheIdentity(lat+.00002,lng-.00002);
assert.deepEqual(id,same);assert(id.slot<4096);assert.equal(id.key.length,64);
assert.equal(await reverseCacheRead(db,id,lat,lng,10),null);
assert.equal(await reverseCacheWrite(db,id,[],lat,lng,10),false);
assert.equal(await reverseCacheWrite(db,id,[...rows,{...rows[0],street:'Otra calle'}],lat,lng,10),false);
assert.equal(await reverseCacheWrite(db,id,rows,lat,lng,10),true);
const raw=sqlite.prepare('SELECT * FROM reverse_reference_cache').get();
assert(!raw.payload.includes('accountId')&&!raw.payload.includes('private')&&!raw.payload.includes('distanceMeters'));
const near=await reverseCacheRead(db,same,lat+.00002,lng-.00002,11);
assert(near[0].distanceMeters>0);assert.equal(near[0].source,'Geoapify');
assert.equal(await reverseCacheRead(db,id,lat,lng,10+7*86400),null);
assert.equal(await reverseCacheRead(db,id,lat+.01,lng,11),null);
assert.equal(await reverseCacheRead({prepare(){throw Error('D1 down')}},id,lat,lng,11),null);
assert.equal(await reverseCacheWrite(db,id,rows,lat,lng),true);
let network=0;
const req=new Request('https://example.invalid/api/direcciones?mode=reverse&lat='+lat+'&lng='+lng);
const hit=await viaReverseRace(req,{POI_CACHE:db,VIA_POI_API:{fetch:async()=>{network++;throw Error('unexpected')}}},{fetch:async()=>{network++;throw Error('unexpected')}},{});
assert.equal(hit.headers.get('X-Via-Reverse-Cache'),'HIT');assert.equal(network,0);
sqlite.exec('DELETE FROM reverse_reference_cache');let writes=[];
const ok=await viaReverseRace(req,{POI_CACHE:db,VIA_POI_API:{fetch:async()=>{throw Error('unexpected')}}},{fetch:async()=>new Response(JSON.stringify({results:rows}))},{waitUntil(p){writes.push(p)}});
assert.equal(ok.status,200);await Promise.all(writes);assert.equal(writes.length,1);assert(await reverseCacheRead(db,id,lat,lng));
console.log('VIA_REVERSE_CACHE_UNIT_PASS real SQLite schema, TTL, sanitized rows, ambiguity, distance, cache hit skips both providers, D1 outage safe');
